"""Fit an all-pass cascade for the dry path so its phase tracks the wet path's fixed
linear filters (BB input coupling HPFs + bump + dip, interstage coupling cap, DC blocker).
Writes the sections into plugin/Source/DryPhase.h."""
import json, sys
import numpy as np
from scipy.signal import freqz
from scipy.optimize import least_squares

sys.path.insert(0, "model")
import model as M

SR = 48000
j = json.load(open("model/final_fit.json"))
eq = json.load(open("model/eq_fit.json"))["eq"]
st1 = j["st1"]
f = np.geomspace(15, 20000, 600)


def resp(b, a, sr=SR):
    return freqz(b, a, worN=f, fs=sr)[1]


H = np.ones(len(f), complex)
for b, a in (M.onepole_hpf(eq["hp1_fc"]), M.biquad_hpf(eq["hp_fc"], eq["hp_q"]),
             M.biquad_peak(eq["bump_fc"], eq["bump_db"], eq["bump_q"]), M.biquad_peak(eq["dip_fc"], eq["dip_db"], eq["dip_q"]),
             M.biquad_hpf(1.5, 0.9)):
    H *= resp(b, a)
H *= resp(*M.biquad_hpf(st1["hp_fc"], st1["hp_q"], SR * 4), sr=SR * 4)   # interstage cap runs at 4x
target = H / np.abs(H)
# weight: where the wet path actually has level, emphasising the lows (where the mismatch is)
w = np.abs(H) * (1.0 + 3.0 * (f < 300))


def allpass(f0, q):
    w0 = 2 * np.pi * f0 / SR; al = np.sin(w0) / (2 * q); c = np.cos(w0)
    b = np.array([1 - al, -2 * c, 1 + al]) / (1 + al); a = np.array([1 + al, -2 * c, 1 - al]) / (1 + al)
    return b, a


def ap1(fc):
    k = np.tan(np.pi * fc / SR)
    return np.array([(k - 1) / (k + 1), 1.0]), np.array([1.0, (k - 1) / (k + 1)])


def build(v, n2):
    A = np.ones(len(f), complex)
    for i in range(n2):
        A *= resp(*allpass(10 ** v[2 * i], v[2 * i + 1]))
    return A


def res(v, n2):
    A = build(v, n2)
    e = (A - target) * w
    return np.r_[e.real, e.imag]


best = None
rng = np.random.default_rng(1)
for n2 in (1, 2, 3, 4):
    for trial in range(30):
        v0 = []
        for i in range(n2):
            v0 += [rng.uniform(np.log10(5), np.log10(200)), rng.uniform(0.3, 1.5)]
        lo = [np.log10(2), 0.15] * n2
        hi = [np.log10(1000), 3.0] * n2
        r = least_squares(res, np.clip(v0, lo, hi), bounds=(lo, hi), args=(n2,), max_nfev=400)
        A = build(r.x, n2)
        err = np.degrees(np.abs(np.angle(A / target)))
        score = np.max(err[(f >= 25) & (f <= 20000)]) + 2.0 * n2   # small penalty per extra section
        if best is None or score < best[0]:
            best = (score, n2, r.x, err)
score, n2, v, err = best
print(f"best: {n2} 2nd-order all-pass sections, max phase error 25 Hz-20 kHz {score - 2.0 * n2:.1f} deg")
for fr in (20, 25, 30, 40, 60, 100, 200, 500, 1000, 5000, 10000, 20000):
    i = np.argmin(np.abs(f - fr))
    s = abs(1 + np.exp(1j * np.radians(err[i]))) / 2
    print(f"   {fr:6d} Hz: residual {err[i]:5.1f} deg -> 50/50 sum loss {20 * np.log10(s):6.2f} dB")
secs = [(10 ** v[2 * i], v[2 * i + 1]) for i in range(n2)]
src = "#pragma once\n// GENERATED by model/fit_dry_allpass.py - all-pass sections that give the dry path the same\n"
src += "// low-frequency phase as the wet path's fixed filters, so Dry + Wet sum without cancelling.\n"
src += "namespace DryPhase\n{\nstruct Section { double fc, q; };\n"
src += f"inline constexpr Section secondOrder[{n2}] = {{ " + ", ".join(f"{{ {a:.6f}, {b:.6f} }}" for a, b in secs) + " };\n"
src += f"inline constexpr int numSecondOrder = {n2};\n}}\n"
open("plugin/Source/DryPhase.h", "w").write(src)
print(src)
