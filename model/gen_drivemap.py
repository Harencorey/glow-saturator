"""Turn the per-drive fits into plugin/Source/DriveMap.h.

The five measured drive settings are interpolated with a monotone cubic (PCHIP)
into a 101-point table; the plugin linearly interpolates that table, so the
Drive knob sweeps smoothly between the measured points.
"""
import json
import os
import numpy as np
from scipy.interpolate import PchipInterpolator

DRIVES = [0, 25, 50, 75, 100]
KEYS = ["pre_db", "post_db", "sharp", "asym", "k2"]

import sys
joint = json.load(open(sys.argv[1]))  # e.g. model/joint_fit_sgn1.json
fits = {d: joint["per"][str(d)] for d in DRIVES}
st1 = joint["st1"]
eq = json.load(open("model/eq_fit.json"))["eq"]
post = json.load(open("model/post_fit.json")) if os.path.exists("model/post_fit.json") else {"dc_fc": 1.5, "dc_q": 0.9}

xs = np.linspace(0, 100, 101)
cols = {k: PchipInterpolator(DRIVES, [fits[d][k] for d in DRIVES])(xs) for k in KEYS}
cols["sharp"] = np.maximum(cols["sharp"], 1.2)

rows = ",\n".join(
    "        { %.5ff, %.5ff, %.5ff, %.6ff, %.6ff }" % tuple(cols[k][i] for k in KEYS) for i in range(len(xs)))

src = f"""#pragma once
// GENERATED by model/gen_drivemap.py from the fits in model/*.json - do not edit by hand.
#include <cmath>

namespace DriveMap
{{
struct Shape {{ float preDb, postDb, sharp, asym, k2; }};

struct EQ {{ double hp1Fc, hpFc, hpQ, bumpFc, bumpDb, bumpQ, dipFc, dipDb, dipQ; }};
inline constexpr EQ eq {{ {eq['hp1_fc']:.6f}, {eq['hp_fc']:.6f}, {eq['hp_q']:.6f}, {eq['bump_fc']:.6f}, {eq['bump_db']:.6f},
                          {eq['bump_q']:.6f}, {eq['dip_fc']:.6f}, {eq['dip_db']:.6f}, {eq['dip_q']:.6f} }};

// input tube stage (shared by every Drive setting)
struct Stage1 {{ float inGain, sharp, asym, k2; double hpFc, hpQ; }};
inline constexpr Stage1 st1 {{ {10 ** (-st1['in_db'] / 20):.6f}f, {st1['sharp']:.6f}f, {st1['asym']:.6f}f, {st1['k2']:.6f}f,
                              {st1['hp_fc']:.6f}, {st1['hp_q']:.6f} }};

struct Post {{ double dcFc, dcQ; }};
inline constexpr Post post {{ {post['dc_fc']:.6f}, {post['dc_q']:.6f} }};

inline constexpr Shape table[101] = {{
{rows}
}};

// drive: 0..100
inline Shape at (float drive) noexcept
{{
    const float x = drive < 0.0f ? 0.0f : (drive > 100.0f ? 100.0f : drive);
    const int i = (int) x >= 100 ? 99 : (int) x;
    const float t = x - (float) i;
    const Shape& a = table[i];
    const Shape& b = table[i + 1];
    auto L = [t] (float p, float q) {{ return p + (q - p) * t; }};
    return {{ L (a.preDb, b.preDb), L (a.postDb, b.postDb), L (a.sharp, b.sharp), L (a.asym, b.asym), L (a.k2, b.k2) }};
}}
}} // namespace DriveMap
"""
open("plugin/Source/DriveMap.h", "w").write(src)
print("wrote plugin/Source/DriveMap.h", st1)
for d in DRIVES:
    print(d, {k: round(fits[d][k], 3) for k in KEYS})
